/// How a primitive is aligned horizontally within the space its parent
/// gives it. `left` (index 0) is this field's default/omittable value —
/// see EnumField.
enum HorizontalAlignment { left, center, right, expand }

/// How a primitive is aligned vertically within the space its parent gives
/// it. `top` (index 0) is this field's default/omittable value — see
/// EnumField.
enum VerticalAlignment { top, middle, bottom, expand }
